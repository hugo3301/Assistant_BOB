import {writeFileSync,readFileSync} from 'node:fs';
import {adminClient} from '../src/admin/client.mjs';
const target=new URL('../src/admin/client-source.mjs',import.meta.url);
const code='('+adminClient.toString().replace(/\r\n/gu,'\n')+')();';
const generated='// Generated by scripts/build-admin-source.mjs; do not edit.\nexport const ADMIN_CLIENT = '+JSON.stringify(code)+';\n';
if(process.argv.includes('--check')){if(readFileSync(target,'utf8').replace(/\r\n/gu,'\n')!==generated)throw Error('Admin browser source is stale; run node scripts/build-admin-source.mjs');}
else writeFileSync(target,generated);
